#!/usr/bin/env python3
"""Code overlays of the M4 game (src/m4/ovl.asm).

  ovltool.py equ MAIN.sym OVERLAY.asm BASEDIR OUT.inc
      every symbol of the resident program (pasmo symbol file) as an equ, except the labels the overlay source
      (and the files it includes, resolved from BASEDIR as pasmo does from its working directory; OUT.inc itself is
      skipped) defines itself.
  ovltool.py pack MAIN.sym OUT.bin OVERLAY.bin...
      the RAM-disk image of the overlays, to be written at OVL_RD_PAGE:OVL_RD_TAB: the table (OVL_MAX entries of
      8 bytes: page, address, length, window address, 0) and then the images. Each overlay's id and window come from
      its own symbol file (OVERLAY.sym: ovl_id, ovl_entry). An overlay that defines ovl_rd_page, ovl_rd_addr and
      ovl_rd_last lives there instead (its .bin is written to that place separately): only its table entry is here.
  ovltool.py equp OVERLAY.sym PREFIX OUT.inc NAME...
      the named labels of an overlay as equs PREFIX + NAME (code laid over the game calls into a loaded overlay:
      src/duel/duel.asm and the text overlay, build/duel_text.inc)."""
import os, re, struct, sys

def syms(path):
    d = {}
    for line in open(path):
        m = re.match(r'(\S+)\s+EQU\s+([0-9A-Fa-f]+)H', line.strip())
        if m: d[m.group(1)] = int(m.group(2), 16)
    return d

LABEL = re.compile(r'([A-Za-z_][A-Za-z0-9_]*)(:|\s|$)')
INCLUDE = re.compile(r'\s+include\s+"([^"]+)"', re.I)

def defined(path, base, seen=None):
    """labels defined in column 0 of path and its includes (missing files: skipped, e.g. the generated include)"""
    seen = set() if seen is None else seen
    names = set()
    if path in seen or not os.path.exists(path): return names
    seen.add(path)
    for line in open(path):
        line = line.split(';')[0].rstrip('\n')
        m = INCLUDE.match(line)
        if m:
            names |= defined(os.path.normpath(os.path.join(base, m.group(1))), base, seen); continue
        if line[:1].strip():
            m = LABEL.match(line)
            if m: names.add(m.group(1))
    return names

def cmd_equ(mainsym, src, base, out):
    S = syms(mainsym)
    own = defined(os.path.abspath(src), os.path.abspath(base), {os.path.abspath(out)})   # (not the include being made)
    lines = ['; generated by tools/ovltool.py from %s for %s: the resident symbols (do not edit)' % (mainsym, src)]
    lines += ['%-31s equ     0x%04x' % (k, v & 0xFFFF) for k, v in sorted(S.items()) if k not in own]
    open(out, 'w').write('\n'.join(lines) + '\n')

def cmd_equp(sym, prefix, out, names):
    S = syms(sym)
    lines = ['; generated by tools/ovltool.py from %s: labels of the overlay (do not edit)' % sym]
    lines += ['%-31s equ     0x%04x' % (prefix + k, S[k]) for k in names]
    open(out, 'w').write('\n'.join(lines) + '\n')

def cmd_pack(mainsym, out, bins):
    M = syms(mainsym)
    page, tab, n, end = M['OVL_RD_PAGE'], M['OVL_RD_TAB'], M['OVL_MAX'], M['OVL_RD_LAST'] + 1
    windows = [(M['OVL_W1'], M['OVL_W1_END'], 'W1'), (M['OVL_W2'], M['OVL_W2_END'], 'W2'), (M['OVL_WF'], M['OVL_W2_END'], 'WF')]
    if 'OVL_WL' in M: windows += [(M['OVL_WL'], M['OVL_WL_END'], 'WL'), (M['OVL_WL2'], M['OVL_WL2_END'], 'WL2')]
    table = bytearray(8 * n); images = b''; addr = tab + 8 * n
    for b in bins:
        S = syms(os.path.splitext(b)[0] + '.sym'); img = open(b, 'rb').read()
        k, at = S['ovl_id'], S['ovl_entry']
        assert k < n and not any(table[8 * k:8 * k + 8]), (b, 'overlay id %d twice or too large' % k)
        w = [w for w in windows if w[0] == at]
        assert w, (b, 'not at a window: %04X' % at)
        lo, hi, name = w[0]
        assert at + len(img) <= hi, (b, 'larger than its window')
        if 'ovl_rd_page' in S:          # (an image with its own place: written there separately, only the entry here)
            p, a = S['ovl_rd_page'], S['ovl_rd_addr']
            assert a + len(img) <= S['ovl_rd_last'] + 1, (b, 'larger than its RAM-disk place')
            table[8 * k:8 * k + 8] = struct.pack('<BHHHB', p, a, len(img), at, 0)
            print('overlay %d %s: %d bytes at %s %04X-%04X (%d of %d, %d free), RAM disk %d:%04X-%04X (its own place, %d free)'
                  % (k, os.path.basename(b), len(img), name, at, at + len(img) - 1, len(img), hi - lo, hi - lo - len(img), p, a,
                     a + len(img) - 1, S['ovl_rd_last'] + 1 - a - len(img)))
            continue
        assert addr + len(img) <= end, (b, 'the RAM-disk overlay area is full')
        table[8 * k:8 * k + 8] = struct.pack('<BHHHB', page, addr, len(img), at, 0)
        print('overlay %d %s: %d bytes at %s %04X-%04X (%d of %d, %d free), RAM disk %d:%04X'
              % (k, os.path.basename(b), len(img), name, at, at + len(img) - 1, len(img), hi - lo, hi - lo - len(img), page, addr))
        images += img; addr += len(img)
    open(out, 'wb').write(bytes(table) + images)
    print('%s: %d bytes for RAM disk %d:%04X-%04X (%d free up to %04X)' % (out, len(table) + len(images), page, tab, addr - 1, end - addr, end - 1))

if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['equ'] and len(a) == 5: cmd_equ(*a[1:])
    elif a[:1] == ['equp'] and len(a) >= 5: cmd_equp(a[1], a[2], a[3], a[4:])
    elif a[:1] == ['pack'] and len(a) >= 4: cmd_pack(a[1], a[2], a[3:])
    else: sys.exit(__doc__)
