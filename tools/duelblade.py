#!/usr/bin/env python3
"""Player 2's blade kept white (docs/duel-design.md 16.4, the user's choice S1, 2026-11-13).

Seven of the kid's body images carry the blade inside the body image (drawing the sword, the strike's start, sheathing).
Player 2's colours (duel.asm d_sdraw, DUEL_LOOK 0: where B is set, R and G cleared) turn its white 15 light blue 9, and
no input colour comes out white. So after player 2's body is drawn in such an image, duel.asm d_blade sets the blade's
pixels white (all four planes) in the compose chunk again.

The blade's pixels: the white pixels of the image inside a band per row (BANDS, from the images: the blade's line as
it runs outside the body; where it enters the body it is white on white for player 1 too and is left to the suit).
The data (staged with the arenas' piece P_w2, read from the RAM disk while drawing): per image the pixel count, then
(dy, dx) per pixel, dx from the image's left in its unmirrored form; the table d_bltab: the image, the data's address,
the mirror constant wb * 8 - 1 (spr_fetch mirrors the whole bytes: a mirrored pixel is at wb * 8 - 1 - dx).

usage: duelblade.py --asm DATA_INC TAB_INC     the data (inside P_w2) and the table rows (duel.asm)
       duelblade.py --render PNG               player 1, player 2 as before, player 2 with the blade white"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
A = os.path.join(ROOT, 'build', 'assets')

# image id (duel_z80 drawn_ids, the descriptor's SD_FRAME): (the frames, {row: (first column, last column)})
BANDS = {
    210: ('209 draw', {4: (0, 5), 5: (3, 10), 6: (10, 15), 7: (14, 21), 8: (20, 25)}),
    211: ('210 draw', {r: (0, 15) for r in range(0, 9)}),
    176: ('152 strike', {r: (0, 10) for r in range(5, 9)}),
    169: ('237 sheathe', {r: (0, 10) for r in range(6, 20)}),
    170: ('238 sheathe', {r: (0, 10) for r in range(7, 13)}),
    171: ('239 sheathe', {r: (0, 6) for r in range(8, 13)}),
    172: ('240 sheathe', {r: (0, 6) for r in range(9, 13)}),
}


def image(pid):
    """(wb, w, h, rows of colours, -1 transparent), unmirrored, as the pack holds it"""
    pack = open(os.path.join(A, 'kid.pack'), 'rb').read(); d = open(os.path.join(A, 'kid.dir'), 'rb').read()[pid * 8:pid * 8 + 8]
    off = (d[0] << 16) | (d[1] << 8) | d[2]; wb, h, flags = d[3], d[4], d[5]; n = wb * h
    if flags & 1:
        mask = pack[off:off + n]; planes = [pack[off + n * (p + 1):off + n * (p + 2)] for p in range(4)]
    else:
        planes = [pack[off + n * p:off + n * (p + 1)] for p in range(4)]
        mask = bytes(planes[0][i] | planes[1][i] | planes[2][i] | planes[3][i] for i in range(n))
    rows = []
    for y in range(h):
        row = []
        for x in range(wb * 8):
            o = y * wb + (x >> 3); bit = 1 << (x & 7)
            row.append(sum(1 << p for p in range(4) if planes[p][o] & bit) if mask[o] & bit else -1)
        rows.append(row)
    return wb, json.load(open(os.path.join(A, 'kid.json')))['images'][str(pid)]['w'], h, rows


def blade(pid):
    """[(dy, dx)]: the blade's white pixels"""
    wb, w, h, rows = image(pid)
    return [(y, x) for y, (c0, c1) in sorted(BANDS[pid][1].items()) for x in range(c0, c1 + 1) if rows[y][x] == 15]


def asm(data_out, tab_out):
    data = ['; generated by tools/duelblade.py: player 2\'s blade pixels (count, then dy, dx), staged in P_w2']
    tab = ['; generated by tools/duelblade.py: d_bltab rows (the image, the data\'s RAM-disk address, wb * 8 - 1)']
    for i, pid in enumerate(sorted(BANDS)):
        px = blade(pid); wb = image(pid)[0]
        assert 0 < len(px) < 256 and all(dx < wb * 8 for _, dx in px)
        data.append('bl_%d:%s db      %d' % (pid, ' ' * (8 - len(str(pid))), len(px)))
        for k in range(0, len(px), 8):
            data.append('                db      ' + ', '.join('%d, %d' % p for p in px[k:k + 8]))
        tab.append('                db      %d' % pid)
        tab.append('                dw      DSTAGE_W2 + bl_%d - P_w2' % pid)
        tab.append('                db      %d' % (wb * 8 - 1))
    open(data_out, 'w').write('\n'.join(data) + '\n'); open(tab_out, 'w').write('\n'.join(tab) + '\n')
    print('the blades: %d images, %d pixels, %d bytes of data (P_w2), %d of table' %
          (len(BANDS), sum(len(blade(p)) for p in BANDS), sum(1 + 2 * len(blade(p)) for p in BANDS), 4 * len(BANDS)))


def p2(c):
    b, r, g, i = c & 1, (c >> 1) & 1, (c >> 2) & 1, (c >> 3) & 1
    if b: r = g = 0
    elif r and not g: r = 0; i = 1
    return b | r << 1 | g << 2 | i << 3


def render(out):
    sys.path.insert(0, HERE)
    from emu import PALETTE
    from PIL import Image, ImageDraw
    pal = [tuple(PALETTE[i * 3:i * 3 + 3]) for i in range(16)]
    S = 4; CW = 44 * S; cols = ['P1 (the kid)', 'P2 before', 'P2 now: the blade white']
    im = Image.new('RGB', (150 + len(cols) * CW, 24 + len(BANDS) * 46 * S), (32, 32, 32)); dr = ImageDraw.Draw(im)
    for k, t in enumerate(cols): dr.text((150 + k * CW + 4, 6), t, fill=(255, 255, 0))
    for n, pid in enumerate(BANDS):
        y0 = 24 + n * 46 * S; wb, w, h, rows = image(pid); bl = set(blade(pid))
        dr.text((4, y0 + 60), 'frame %s\nimage %d\n%d pixels' % (BANDS[pid][0], pid, len(bl)), fill=(255, 255, 255))
        for k in range(3):
            for y, row in enumerate(rows):
                for x, c in enumerate(row):
                    if c < 0: continue
                    v = c if k == 0 else p2(c) if k == 1 or (y, x) not in bl else 15
                    X = 150 + k * CW + (wb * 8 - 1 - x) * S; Y = y0 + y * S     # (mirrored: player 2 faces left)
                    dr.rectangle([X, Y, X + S - 1, Y + S - 1], fill=pal[v])
    im.save(out)


if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['--asm']: asm(a[1], a[2])
    elif a[:1] == ['--render']: render(a[1])
    else: sys.exit(__doc__)
