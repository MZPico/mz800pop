#!/usr/bin/env python3
"""Generate unrolled Z80 routines for the planar graphics kernel -> src/m1/kernel_gen.inc

shift_row variants: in DE = source row (w bytes; for mirror: its LAST byte), IY = dest cell row + plane
  (interleaved cells: byte k of the output row goes to IY+4k, so the four planes of a pixel column are adjacent),
  H = lo-table page (hi table = next page), B = lo-table page (mirror variants), C = scratch.
  Table layout: TABBASE page 0 = bit-reverse table; page 2s = lo[s], page 2s+1 = hi[s] (s = 1..7).
  lo[s][b] = (b << s) & 0xFF, hi[s][b] = b >> (8 - s)   (bit 0 = leftmost pixel, shift = move right)
cmp_n: HL = (maskinv,data) pairs, DE = compose dest; n bytes: dest = (dest & maskinv) | data
fill_n: HL = dest, A = 0; n bytes
cpy_n: HL = src, DE = dest; n bytes (plain copy via LDI)
"""
import sys
MAXW = 7
out = ['; generated by tools/gen_kernel.py - do not edit']
# ---- shift rows
for w in range(1, MAXW + 1):
    for mirror in (0, 1):
        for zero in (0, 1):
            name = 'shr_w%d_m%d_s%d' % (w, mirror, zero)
            out.append(name + ':')
            if not zero: out.append('                ld      c, 0')
            for k in range(w):
                out.append('                ld      a, (de)')
                out.append('                ' + ('dec' if mirror else 'inc') + '     de')
                if mirror:
                    out += ['                ld      l, a', '                ld      h, TABBASE >> 8',
                            '                ld      a, (hl)']
                if zero:
                    out.append('                ld      (iy+%d), a' % (4*k))
                else:
                    if mirror: out.append('                ld      h, b')
                    out += ['                ld      l, a', '                ld      a, (hl)', '                or      c',
                            '                ld      (iy+%d), a' % (4*k), '                inc     h',
                            '                ld      c, (hl)', '                dec     h']
            out.append('                ld      (iy+%d), %s' % (4*w, '0' if zero else 'c'))
            out.append('                ret')
out.append('; dispatch: index = ((w-1)*2 + mirror)*2 + (s==0)')
out.append('shr_table:')
for w in range(1, MAXW + 1):
    for mirror in (0, 1):
        for zero in (0, 1):
            out.append('                dw      shr_w%d_m%d_s%d' % (w, mirror, zero))
# ---- fill
for n in range(1, 9):
    out.append('fill_%d:' % n)
    for k in range(n): out += ['                ld      (hl), a', '                inc     hl']
    out.append('                ret')
out.append('fill_table:')
out.append('                dw      0')
for n in range(1, 9): out.append('                dw      fill_%d' % n)
# ---- blit whole rows, all four planes of a row back to back (the beam sees a row old or new, never half):
#   HL = compose row (plane stride 512, row stride 8), DE = VRAM row (stride 40), A = rows
for n in range(1, 9):
    out.append('blq_%d:' % n)
    out.append('                ex      af, af\'')
    out.append('blq_%d_r:' % n)
    for p in (1, 2, 4, 8):
        out += ['                ld      a, %d' % p, '                out     (0xcc), a']
        for k in range(n): out.append('                ldi')
        hl, de = (512 - n, -n) if p != 8 else (8 - n - 3 * 512, 40 - n)
        out += ['                ld      bc, %d' % hl, '                add     hl, bc', '                ex      de, hl',
                '                ld      bc, %d' % de, '                add     hl, bc', '                ex      de, hl']
    out += ['                ex      af, af\'', '                dec     a', '                ret     z',
            '                ex      af, af\'', '                jp      blq_%d_r' % n]
out.append('blq_table:')
out.append('                dw      0')
for n in range(1, 9): out.append('                dw      blq_%d' % n)
# ---- masked combine rows: HL = dst, BC = inverted mask rows; n bytes, both advance (mode 1, the masked copy, has its
#   own row chain in gfx.asm, lmx_ent: M8a part 20)
#   cm2: dst &= ~m     cm3: dst |= m
for n in range(1, 9):
    out.append('cm2_%d:' % n)
    for k in range(n): out += ['                ld      a, (bc)', '                and     (hl)', '                ld      (hl), a', '                inc     hl', '                inc     bc']
    out.append('                ret')
    out.append('cm3_%d:' % n)
    for k in range(n): out += ['                ld      a, (bc)', '                cpl', '                or      (hl)', '                ld      (hl), a', '                inc     hl', '                inc     bc']
    out.append('                ret')
for m in (2, 3):
    out.append('cm%d_table:' % m)
    out.append('                dw      0')
    for n in range(1, 9): out.append('                dw      cm%d_%d' % (m, n))
# ---- pushrows: 256 x push de (512 bytes); enter at pushrows + 256 - count with SP and IX (continuation) set
out.append('pushrows:')
for k in range(256): out.append('                push    de')
out.append('                jp      (ix)')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print('generated', sys.argv[1], len(out), 'lines')
