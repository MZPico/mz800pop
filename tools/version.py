#!/usr/bin/env python3
"""The port's version: VERSION (the repository's root, one line: a semantic version MAJOR.MINOR.PATCH, optionally with
a -suffix of letters, digits, dots and hyphens, e.g. 0.9.0 or 1.0.0-rc.1) -> an include for src/boot/bootscr.asm: the
loading screen's version line ("V0.9.0", centred under the credit line, colour 7). Anything else fails the build.
The loader's font has upper-case letters, digits, '.' and '-' only: a suffix is shown in upper case.

usage: version.py OUT.inc        (version.py --print: the version alone)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEMVER = re.compile(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z][0-9A-Za-z.-]*)?')
ROW = 72                # the version line's pixel row (the title 48, the credit 60)

def version():
    text = open(os.path.join(ROOT, 'VERSION')).read().strip()
    if not SEMVER.fullmatch(text):
        raise SystemExit('VERSION: "%s" is not a semantic version (MAJOR.MINOR.PATCH, optionally -suffix)' % text)
    return text

def screen_text(v):
    """the line as the loading screen shows it"""
    return 'V' + v.upper()

def column(t):
    """the byte column that centres t on the 40 columns (as the title and the credit)"""
    if len(t) > 40: raise SystemExit('VERSION: "%s" is too long for the screen (40 characters)' % t)
    return (40 - len(t)) // 2

def main():
    if sys.argv[1:] == ['--print']:
        print(version()); return
    if len(sys.argv) != 2: raise SystemExit(__doc__)
    t = screen_text(version())
    out = ('; generated by tools/version.py from VERSION: the loading screen\'s version line (print_at)\n'
           'msg_ver:        dw      %d * 40 + %d\n'
           '                db      7, "%s", 0\n' % (ROW, column(t), t))
    tmp = sys.argv[1] + '.tmp'
    open(tmp, 'w').write(out)
    os.replace(tmp, sys.argv[1])

if __name__ == '__main__':
    main()
